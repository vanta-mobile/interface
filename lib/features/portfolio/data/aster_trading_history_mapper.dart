import '../domain/futures_history.dart';
import '../domain/trading_history.dart';

TradingHistoryRecord mapAsterTradingRecord(FuturesHistoryRecord row) => switch (row) {
  FuturesOrderRecord r => HistoryOrder(
    symbol: r.symbol,
    time: r.time,
    id: r.orderId,
    side: r.side,
    positionSide: r.positionSide,
    type: r.originalType ?? r.type,
    status: r.status,
    executed: r.executed,
    quantity: r.quantity,
    price: r.price,
    averagePrice: r.averagePrice,
    quoteFilled: r.quoteFilled,
    reduceOnly: r.reduceOnly,
    closePosition: r.closePosition,
    updatedAt: r.updatedAt,
    stopPrice: r.stopPrice,
    activationPrice: r.activationPrice,
    callbackRate: r.callbackRate,
    workingType: r.workingType,
  ),
  FuturesTradeRecord r => HistoryFill(
    symbol: r.symbol,
    time: r.time,
    id: r.tradeId,
    orderId: r.orderId,
    side: r.side,
    positionSide: r.positionSide,
    price: r.price,
    quantity: r.quantity,
    notional: r.quoteQuantity,
    fee: r.commission,
    feeAsset: r.commissionAsset,
    realizedPnl: r.realizedPnl,
    maker: r.maker,
  ),
  FuturesIncomeRecord r => HistoryTransaction(
    symbol: r.symbol,
    time: r.time,
    id: r.key,
    type: r.type,
    asset: r.asset,
    amount: r.income,
  ),
};
